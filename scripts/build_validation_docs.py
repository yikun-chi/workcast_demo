"""Regenerate the documentation's numeric claims from the current evaluations."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]


def build():
    trip = json.loads((ROOT / "runs/trip/evaluation.json").read_text())
    bpi = json.loads((ROOT / "runs/bpi19/evaluation.json").read_text())
    if not trip.get("paired_comparison") or not bpi.get("business_validation"):
        print("Documentation awaits current evaluations for both instances")
        return
    tm = {m["id"]: m for m in trip["metrics"]}
    bm = {m["id"]: m for m in bpi["metrics"]}
    paired = {r["scenario"]: r for r in trip["paired_comparison"]}
    bs = {r["scenario"]: r for r in bpi["scenario_comparison"]}
    comp = trip["comparators"]
    text = ["# Validation of the two instances", "",
            "Numeric claims are generated by `scripts/build_validation_docs.py` from the current evaluations. "
            "The framing is observed before → change → actual outcome, non-simulation prediction and simulation → alternative behavior.", "",
            "## Trip.com", "",
            "The prediction uses pretreatment employee covariates, prior performance ratings and sourced behavioral priors. "
            "Neither arm's post-policy outcomes nor the observed endline response rate calibrates the simulation. "
            f"The paper reports **{comp['no_change_pct']:.1f}% attrition in the Airfare and IT divisions during the preceding six months** "
            f"([source]({comp['history']['source_url']})). This division-level aggregate appears in the Before section. "
            "The download omits individual pre-period departures and their denominator. Pre-policy satisfaction is unavailable. "
            "The office-only group was observed alongside the hybrid group after the change and is used to measure the policy impact.", "",
            "Daily choices use random draws keyed to employee and decision time. Trace sampling and survey noise have separate streams. "
            "Expected quits are estimated by summing hazards while employees remain at risk; a stopped survival product would be biased. "
            "Ordinal performance transitions preserve the pretreatment grade distribution. Gender is excluded from behavior, imputation and synthetic assignments.", "",
            "| Outcome | Simulation | Actual | Absolute error |", "|---|---:|---:|---:|"]
    for m in trip["metrics"]:
        if m.get("primary") or m["id"] in ("attrition_control_pct", "attrition_treatment_pct", "takeup_treatment"):
            text.append(f"| {m['label']} | {m['simulated']:.4f} | {m['actual']:.4f} | {m['abs_error']:.4f} |")
    text += ["", f"Point predictions are ensemble expectations over {trip['protocol']['seeds']} seeds. "
             "Predictive intervals use realized outcomes. "
             "Absolute attrition levels remain sensitive to the external turnover prior. Manager effects remain uncertain.", "",
             f"Other predictions use historical information only. No change carries forward {comp['no_change_pct']:.1f}% attrition and assumes zero policy impact. "
             f"The simple two-day calculation scales the earlier four-day study's approximately {100*comp['study']['relative_attrition_reduction']:.0f}% retention benefit: "
             f"{comp['no_change_pct']:.1f}% × (1 − {100*comp['study']['relative_attrition_reduction']:.0f}% × {comp['home_days']}/{comp['study']['home_days_per_week']}) "
             f"= {comp['proportional_days_pct']:.2f}% attrition, or {comp['proportional_days_effect_pp']:.2f} percentage points of policy impact "
             f"([earlier study]({comp['study']['source_url']})). Proportional scaling across schedules, jobs and periods is an explicit assumption. "
             "This second method is used only for overall attrition. The simulation's behavioral parameters and saved predictions are unchanged; "
             "the newly documented historical aggregate supplies context and comparison calculations, not a refit of the turnover prior.", "",
             "This is a retrospective evaluation. The inherited prior revision log records earlier comparison and selection against experiment outcomes, "
             "so neither CI inclusion nor the close headline estimate establishes untouched prospective accuracy.", "",
             f"**Alternative: hybrid for everyone.** The same {paired['baseline']['seeds']} seeds in both scenarios give expected company-wide attrition "
             f"of {paired['baseline']['attrition_pct_all']:.2f}% under the experiment arrangement and {paired['hybrid_for_all']['attrition_pct_all']:.2f}% under universal eligibility. "
             "This is a simulated alternative, not an observed causal estimate.", "",
             "## Procurement purchase-to-pay", "",
             "The process specification is selected using a January–June fit and July–August validation windows, then refitted through August 31. "
             "`calibration/fit.yaml` records the boundaries. The model's joint cumulative-incidence curves retain censored waiting cases, condition on previous activity and match state, "
             "and apply the payment calendar to cause-specific hazards. Roles are inferred from events before the prediction cutoff.", "",
             "Before-policy windows are observed only and end before September 1. After-policy predictions continue each case from its observed prefix for fourteen days. "
             "Actual arrivals are supplied as exogenous inputs; all subsequent events are hidden. This is conditional continuation, not an August-only prediction of every later arrival or organizational change. "
             "All business metrics use the same eligible cases and horizon on both sides.", "",
             "| Business outcome | Before, actual | After, actual | Simulation |", "|---|---:|---:|---:|"]
    for mid in ("completion_14d", "median_cycle_hours", "exception_rate", "handoffs_per_case", "events_per_week"):
        m = bm[mid]
        before = bpi["periods"]["before"]["metrics"][mid]["actual"]
        unit = f" ({m['unit']})" if m['unit'] else ""
        text.append(f"| {m['label']}{unit} | {before:.3f} | {m['actual']:.3f} | {m['simulated']:.3f} |")
    text += ["", "| Outcome | Simulation MAE | Best non-simulation MAE | Error reduction |", "|---|---:|---:|---:|"]
    for row in bpi["business_validation"]:
        unit = bm[row['id']]['unit']
        unit = 'pp' if unit == '%' else unit
        label = bm[row['id']]['label'] + (f" ({unit})" if unit else "")
        text.append(f"| {label} | {row['simulation_mae']:.3f} | {row['baseline_mae'][row['best_baseline']]:.3f} ({row['best_baseline'].replace('_', ' ')}) | {row['error_reduction_pct']:.1f}% |")
    text += ["", "MAE is computed separately for each prediction window and then averaged, avoiding cancellation of opposite errors. "
             "Comparators are the observed pre-policy period carried forward, the pre-policy historical average, and carry-forward scaled by staffing. "
             "The best comparator is selected separately for each outcome. Negative error reduction means the simulation loses.", "",
             f"Next-activity accuracy is {bm['next_activity_accuracy']['simulated']:.2f}% versus {bm['next_activity_accuracy']['baseline']:.2f}% for the best prefix Markov model trained on the same data. "
             "This diagnostic is secondary to business-outcome accuracy.", "",
             f"**Alternative: no workforce expansion.** Matching cutoffs and seeds give completion of {bs['baseline']['completion_rate_14d']:.2f}% "
             f"under observed staffing and {bs['no_expansion']['completion_rate_14d']:.2f}% under the alternative. "
             "The staffing intervention is simulated. Concurrent changes in order mix prevent interpreting the observed period difference as a staffing-only causal effect.", "",
             "## Reproduction", "", "Install dependencies and download the pinned inputs first; see [setup](setup.md). These commands normalize the data, regenerate both evaluations and reports, and verify the results.", "", "```bash", "uv run orgsim demo",
             "uv run --extra dev pytest -q", "uv run python scripts/check_bpi19_results.py", "```", "",
             "To reproduce model-selection validation after normalization, first run `uv run python instances/bpi19/ingest/run.py --training-end 2018-07-01`, "
             "then `uv run python instances/bpi19/ingest/audit/validate_cutoffs.py`; restore the final pre-policy fit with `uv run orgsim ingest bpi19` afterward. "
             "The validation harness rejects overlapping calibration or any validation window extending beyond the change date.", ""]
    from orgsim.instances import get_instance
    from orgsim.evaluation.exploration import report_sections
    exploration_text = []
    for instance in ("trip", "bpi19"):
        for section in report_sections(get_instance(instance)):
            exploration_text += [f"## {instance}: {section['heading']}", "", section["body"], ""]
    position = text.index("## Reproduction")
    text[position:position] = exploration_text
    (ROOT / "docs/validation.md").write_text("\n".join(text))
    readme = ROOT / "README.md"
    lines = readme.read_text().splitlines()
    for i, line in enumerate(lines):
        if line.startswith("| `trip` |"):
            m = tm["attrition_itt_pp"]
            lines[i] = f"| `trip` | Trip.com: two work-from-home days a week? | Attrition effect {m['simulated']:.2f} pp predicted vs {m['actual']:.2f} pp actual; retrospective evaluation; neither group's post-change outcomes used for calibration |"
        if line.startswith("| `bpi19` |"):
            wins = [bm[r['id']]['label'].lower() for r in bpi['business_validation'] if r['beats_best_baseline']]
            lines[i] = f"| `bpi19` | Purchase-to-pay: predict operations after the workforce expansion | Lower error across prediction windows than the best non-simulation comparator on {len(wins)} of {len(bpi['business_validation'])} business outcomes; details in [validation](docs/validation.md) |"
    readme.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    build()
