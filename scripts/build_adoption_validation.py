"""Write docs/validation_<id>.md and runs/<id>/value_inputs.json for an adoption-world instance from
runs/<id>/evaluation.json. Every number is read from the evaluation; nothing is typed in by hand. Instance-specific
prose without numbers (data notes, limitations) comes from the instance's evaluation/protocol.yaml.

    uv run python scripts/build_adoption_validation.py btos_ai
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from orgsim.instances import get_instance  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("instance")
    a = ap.parse_args()
    ctx = get_instance(a.instance)
    ev = json.loads((ctx.runs_dir / "evaluation.json").read_text())
    proto_y = ctx.yaml("evaluation/protocol.yaml")
    proto, acc, labels = ev["protocol"], ev["accuracy"], ev["comparator_labels"]
    sc, unit = float(proto.get("scale", 1.0)), proto.get("unit", "")
    who = ["simulation", *labels]
    name = {"simulation": "Simulation", **{k: v.split(":")[0] for k, v in labels.items()}}
    blocks = {b["id"]: b for b in proto["blocks"]}
    dev = set(proto["dev_cutoffs"])
    wins = ev["windows"]
    held = [w for w in wins if w["cutoff"] not in dev]
    nf = (lambda x: f"{x * sc:,.2f}") if sc != 1 else (lambda x: f"{x:,.0f}")  # noqa: E731

    def table(part: str) -> list[str]:
        rows = [f"| Outcome | Predictions | " + " | ".join(name[k] for k in who) + " | Best other | Error reduction |",
                "|---|---:|" + "---:|" * len(who) + "---|---:|"]
        for bid in [*blocks, "headline"]:
            x = acc[part].get(bid)
            if not x:
                continue
            lab = "Headline (" + ", ".join(blocks[b]["label"] for b in x.get("blocks", proto["headline_blocks"])) + ")" if bid == "headline" else blocks[bid]["label"]
            red = x.get("error_reduction_pct")
            rows.append(f"| {lab} | {x['n_predictions']:,} | " + " | ".join(nf(x["mae"][k]) for k in who) + f" | {name[x['best_baseline']]} | {red:.1f}% |")
        rows.append("")
        rows.append("Accuracy, 100 x (1 - error / mean actual):")
        rows.append("")
        rows.append(f"| Outcome | Mean actual ({unit}) | " + " | ".join(name[k] for k in who) + " |")
        rows.append("|---|---:|" + "---:|" * len(who))
        for bid in [*blocks, "headline"]:
            x = acc[part].get(bid)
            if not x:
                continue
            lab = "Headline" if bid == "headline" else blocks[bid]["label"]
            rows.append(f"| {lab} | {nf(x['mean_actual'])} | " + " | ".join(f"{x['accuracy_pct'][k]:.1f}%" for k in who) + " |")
        return rows

    hh = acc["held_out"]["headline"]
    best = hh["best_baseline"]
    first_h, last_h = held[0]["cutoff_date"], held[-1]["cutoff_date"]
    target_end = max((b.get("target_to") or "") for w in wins for b in w["blocks"].values())
    lines = [f"# Validation: {ctx.meta.get('title', ctx.id)}", "",
             f"Numeric claims are generated by `scripts/build_adoption_validation.py` from `runs/{ctx.id}/evaluation.json`.", "",
             "## Design", "",
             f"{ctx.meta.get('intro', '').strip()}", "",
             f"{len(wins)} cutoffs from {wins[0]['cutoff_date']} to {wins[-1]['cutoff_date']}; the first {len(dev)} were used to make every design "
             f"choice and the other {len(held)} ({first_h} to {last_h}) were run once after the design was frozen in `docs/plans/{ctx.id}_protocol.md`. "
             f"Targets run to {target_end}. Every prediction uses only periods before its cutoff (`tests/test_adoption.py` checks that deleting every later "
             f"outcome leaves the prediction unchanged). The point prediction is the simulation's central path; ranges are the 5th-95th percentile of "
             f"{len(proto['seeds'])} runs per cutoff.", ""]
    for note in proto_y.get("data_notes", []) or []:
        lines += [note.strip(), ""]
    lines += ["## Held-out cutoffs", "", f"Mean absolute error ({unit}); lower is better.", "", *table("held_out"), ""]
    cov = {bid: x["coverage90"] for bid, x in acc["held_out"].items() if bid != "headline" and x}
    lines += ["The simulation's 90% range contained the actual outcome in " + ", ".join(f"{v:.0f}% of predictions {blocks[b]['label']}" for b, v in cov.items()) + ".", ""]
    lines += ["## All cutoffs (development and held out)", "", *table("all"), ""]
    lines += ["## Development cutoffs", "", *table("dev"), ""]
    # where the simulation loses
    lose_c = []
    for w in held:
        for bid, x in w["blocks"].items():
            if bid not in proto["headline_blocks"]:
                continue
            bb = min(labels, key=lambda k: x["mae"][k])
            if x["mae"]["simulation"] > x["mae"][bb]:
                lose_c.append(f"{w['cutoff_date']} ({blocks[bid]['label']}: {nf(x['mae']['simulation'])} vs {nf(x['mae'][bb])}, {name[bb]})")
    n_pairs = sum(1 for w in held for b in w["blocks"] if b in proto["headline_blocks"])
    beat_best = sum(1 for w in held for bid, x in w["blocks"].items() if bid in proto["headline_blocks"] and x["mae"]["simulation"] < x["mae"][best])
    lines += ["## Where the simulation loses", "",
              f"Held-out cutoff and horizon pairs where the simulation's error was below {name[best]}'s (the best other method overall): {beat_best} of {n_pairs}. "
              f"Pairs where at least one other method, chosen after the fact for that pair, had lower error: {len(lose_c)} of {n_pairs}."]
    if lose_c:
        lines += ["", "; ".join(lose_c) + "."]
    # relative errors weight every prediction equally, so late cutoffs with small volumes count as much as early ones
    hr = [r for r in ev["rows"] if r["cutoff"] not in dev and r["block"] in proto["headline_blocks"] and r["actual"]]
    if hr:
        mape = {k: 100 * float(np.mean([abs(r[k] - r["actual"]) / abs(r["actual"]) for r in hr])) for k in who}
        lines += ["", "Mean absolute percentage error, held-out cutoffs, headline horizons (every prediction weighted equally):", "",
                  "| " + " | ".join(name[k] for k in who) + " |", "|" + "---:|" * len(who), "| " + " | ".join(f"{mape[k]:.1f}%" for k in who) + " |"]
    bg = ev.get("by_group") or {}
    if len(bg) > 1:
        lines += ["", f"By group, held-out cutoffs, headline horizons ({unit}):", "",
                  "| Group | Predictions | Mean actual | Simulation | " + name[best] + " |", "|---|---:|---:|---:|---:|"]
        for g in sorted(bg, key=lambda g: -bg[g]["mean_actual"]):
            x = bg[g]
            lines.append(f"| {x['label']} | {x['n']} | {nf(x['mean_actual'])} | {nf(x['simulation'])} | {nf(x[best])} |")
        worse = [bg[g]["label"] for g in bg if bg[g]["simulation"] > bg[g][best]]
        lines += ["", f"The simulation's error is above {name[best]}'s in {len(worse)} of {len(bg)} groups" + (f": {', '.join(worse)}." if worse else ".")]
    lines.append("")
    # a change-point cutoff named in the protocol (for example a product launch)
    cp = proto_y.get("change_cutoff")
    if cp is not None:
        w = next((w for w in wins if w["cutoff"] == int(cp)), None)
        if w:
            rows = [r for r in ev["rows"] if r["cutoff"] == int(cp)]
            lines += [f"## Predicting from before the change ({w['cutoff_date']})", "",
                      "| Outcome | Actual | " + " | ".join(name[k] for k in who) + " |", "|---|---:|" + "---:|" * len(who)]
            for r in rows:
                lines.append(f"| {blocks[r['block']]['label']} | {nf(r['actual'])} | " + " | ".join(nf(r[k]) for k in who) + " |")
            lines += ["", proto_y.get("change_note", "").strip(), ""]
    alt_ids = [k for k in ev["run_ids"] if k != "baseline"]
    if alt_ids:
        from orgsim.evaluation.results import run_docs
        alt = alt_ids[0]
        ad = run_docs(ctx, alt, "summary", ev["run_ids"][alt])
        keys = {(d["headline"]["cutoff"], d["seed"]) for d in ad}
        bd = [d for d in run_docs(ctx, "baseline", "summary", ev["run_ids"]["baseline"]) if (d["headline"]["cutoff"], d["seed"]) in keys]
        mult = sorted({g for d in ad for g in (d["headline"].get("hazard_multipliers") or {})})
        sel = lambda h: [g for g in h["groups"] if not mult or g["group"] in mult]  # noqa: E731
        f = lambda h: float(np.mean([g["central"][-1] for g in sel(h)])) * sc  # noqa: E731
        if ad and bd:
            lines += ["## Alternative (simulated only)", "", f"{ctx.yaml('scenarios/' + alt + '.yaml').get('description', '').strip()}", "",
                      f"At the end of the horizon, averaged over the last {len(keys) // max(1, len(proto['seeds']))} cutoffs and {len(proto['seeds'])} seeds"
                      + (f" in the affected groups ({', '.join(mult)})" if mult else "") + f": {float(np.mean([f(d['headline']) for d in bd])):,.2f} {unit} "
                      f"as it happened in the simulation, {float(np.mean([f(d['headline']) for d in ad])):,.2f} {unit} with the alternative. This is a simulated "
                      "alternative, not an observed change.", ""]
    lines += ["## Limitations", ""]
    for note in proto_y.get("limitations", []) or []:
        lines += [f"- {note.strip()}"]
    lines += ["- Retrospective in part: the world type and the comparators were written with these series visible. The held-out cutoffs were run "
              "once after the design was frozen on the development cutoffs; no design choice was made on them.", ""]
    out = ROOT / "docs" / f"validation_{ctx.id}.md"
    out.write_text("\n".join(lines))
    # value inputs: the headline figures with their exact paths inside evaluation.json
    figs = []
    for part in ("held_out", "all"):
        base = f"accuracy.{part}.headline"
        x = acc[part]["headline"]
        for k in who:
            figs.append({"id": f"{part}_mae_{k}", "label": f"Mean absolute error, {name[k]} ({part.replace('_', '-')} cutoffs, headline horizons)", "value": x["mae"][k] * sc, "unit": unit,
                         "path": f"{base}.mae.{k}", "scale": sc})
        figs += [{"id": f"{part}_mean_actual", "label": "Mean actual level of the outcome", "value": x["mean_actual"] * sc, "unit": unit, "path": f"{base}.mean_actual", "scale": sc},
                 {"id": f"{part}_best_baseline", "label": "Best comparator", "value": x["best_baseline"], "path": f"{base}.best_baseline"},
                 {"id": f"{part}_error_reduction_pct", "label": "Error reduction versus the best comparator", "value": x["error_reduction_pct"], "unit": "%", "path": f"{base}.error_reduction_pct"},
                 {"id": f"{part}_accuracy_simulation", "label": "Accuracy of the simulation, 100 x (1 - error / mean actual)", "value": x["accuracy_pct"]["simulation"], "unit": "%", "path": f"{base}.accuracy_pct.simulation"},
                 {"id": f"{part}_accuracy_best", "label": "Accuracy of the best comparator", "value": x["accuracy_pct"][x["best_baseline"]], "unit": "%", "path": f"{base}.accuracy_pct.{x['best_baseline']}"},
                 {"id": f"{part}_n_predictions", "label": "Predictions scored", "value": x["n_predictions"], "path": f"{base}.n_predictions"}]
    figs += [{"id": "first_cutoff", "label": "First cutoff", "value": wins[0]["cutoff_date"], "path": "windows[0].cutoff_date"},
             {"id": "first_held_out_cutoff", "label": "First held-out cutoff", "value": first_h, "path": f"windows[{len(dev)}].cutoff_date"},
             {"id": "last_cutoff", "label": "Last cutoff", "value": wins[-1]["cutoff_date"], "path": f"windows[{len(wins) - 1}].cutoff_date"},
             {"id": "n_cutoffs", "label": "Cutoffs (development + held out)", "value": len(wins), "path": "protocol.cutoffs"},
             {"id": "n_held_out_cutoffs", "label": "Held-out cutoffs", "value": len(held), "path": "protocol.cutoffs minus protocol.dev_cutoffs"},
             {"id": "n_groups", "label": "Groups scored", "value": len(proto["scored_groups"]), "path": "protocol.scored_groups"}]
    for op in proto_y.get("operational", []) or []:
        figs.append(op)
    vi = {"instance": ctx.id, "source": f"runs/{ctx.id}/evaluation.json", "generated_from": ev["generated"], "unit": unit,
          "note": "Values in `unit` are the evaluation's raw values times `scale`; each `path` is the location inside evaluation.json.", "figures": figs}
    (ctx.runs_dir / "value_inputs.json").write_text(json.dumps(vi, indent=1, default=str))
    print(f"wrote {out.relative_to(ROOT)} and {(ctx.runs_dir / 'value_inputs.json')}")


if __name__ == "__main__":
    main()
