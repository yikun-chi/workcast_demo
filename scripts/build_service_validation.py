"""Write docs/validation_<id>.md and runs/<id>/value_inputs.json for a service-world instance from
runs/<id>/evaluation.json. Every number is read from the evaluation; nothing is typed in by hand.

    uv run python scripts/build_service_validation.py cfpb_complaints
    uv run python scripts/build_service_validation.py nyc311
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]

TEXT = {
    "cfpb_complaints": {
        "title": "Validation: consumer complaints to financial companies (CFPB)",
        "org": "company", "orgs": "companies", "unit": "complaints", "Unit": "Complaints",
        "design": ("At each of {n} Monday cutoffs from {first} to {last}, four weeks apart, the {n_orgs} companies with the most complaints "
                   "in the previous 13 weeks are carried forward for {H} weeks. Each company is split into the products its complaints are "
                   "about (a product with at least 5% of its complaints is its own segment). Every parameter is fitted at each cutoff from "
                   "complaints received before it: the demand specification by backtests at earlier cutoffs whose targets end before it, "
                   "holiday and annual patterns from the weeks before it, and each company's on-time rate and load response from complaints "
                   "whose 15-day response deadline had passed before it. After the cutoff the simulation is told only the U.S. federal "
                   "holiday calendar."),
        "data": ("The CFPB publishes a complaint after the company responds or after 15 days, whichever comes first, and only complaints "
                 "sent to companies for response. The database is not a statistical sample of consumers' experiences. The scored weeks end "
                 "{data_end}, more than 15 days before retrieval, so every complaint in them had been published. A company sees its own "
                 "complaints as they arrive, so the prediction at a cutoff uses every complaint received before it."),
    },
    "nyc311": {
        "title": "Validation: New York City 311 service requests",
        "org": "agency", "orgs": "agencies", "unit": "requests", "Unit": "Requests",
        "design": ("At each of {n} Monday cutoffs from {first} to {last}, four weeks apart, the {n_orgs} agencies with the most 311 requests "
                   "in the previous 13 weeks are carried forward for {H} weeks. Each agency is split into its main complaint types (a type "
                   "with at least the configured share of its requests is its own segment). Every parameter is fitted at each cutoff from "
                   "requests created before it and closures recorded before it: the demand specification by backtests at earlier cutoffs "
                   "whose targets end before it, holiday and annual patterns from the weeks before it, each complaint type's distribution "
                   "of time to close (Kaplan-Meier, censored at the cutoff) and the agency's load response. After the cutoff the "
                   "simulation is told only the U.S. federal holiday calendar."),
        "data": ("NYC Open Data updates the 311 datasets daily, and closing dates fill in over time; the monthly extracts and their "
                 "hashes are in the manifest. Times to close are measured from creation to the recorded closing date; a request still "
                 "open at retrieval counts as not closed. The scored weeks end {data_end}, at least seven weeks before retrieval."),
    },
}


def pct(x, d: int = 1) -> str:
    return "n/a" if x is None or not np.isfinite(x) else f"{x:.{d}f}%"


def num(x, d: int = 2) -> str:
    return "n/a" if x is None or not np.isfinite(x) else f"{x:,.{d}f}"


def err(key: str, measure: str, v) -> str:
    return pct(100 * v, 1) if measure in ("wape", "mape") else f"{num(v, 2)} pts"


def build(iid: str) -> None:
    ev_path = ROOT / "runs" / iid / "evaluation.json"
    ev = json.loads(ev_path.read_text())
    proto, labels = ev["protocol"], ev["comparator_labels"]
    T = TEXT[iid]
    comps = list(labels)
    H = proto["horizon_weeks"]
    held, allc, dev = ev["accuracy"]["held_out"], ev["accuracy"]["all"], ev["accuracy"]["dev"]
    metrics = proto["metrics"]
    groups = proto.get("groups") or {}
    span_end = (pd.Timestamp(proto["held_out_cutoffs"][-1]) + pd.Timedelta(weeks=H) - pd.Timedelta(days=1)).date()
    fmt = {"n": len(proto["cutoffs"]), "first": proto["cutoffs"][0], "last": proto["cutoffs"][-1], "n_orgs": proto["n_orgs"], "H": H, "data_end": proto.get("data_end")}
    L = [f"# {T['title']}", "", f"Numeric claims are generated by `scripts/build_service_validation.py` from `runs/{iid}/evaluation.json`.", ""]
    L += ["## Design", "", T["design"].format(**fmt), "",
          f"The first {len(proto['dev_cutoffs'])} cutoffs ({proto['dev_cutoffs'][0]} to {proto['dev_cutoffs'][-1]}) were used for every design choice "
          f"(variants in `instances/{iid}/calibration/dev_variants.yaml`, run by `scripts/service_dev.py`). The design was then frozen in "
          f"`docs/plans/{iid}_protocol.md` and the {len(proto['held_out_cutoffs'])} held-out cutoffs ({proto['held_out_cutoffs'][0]} to "
          f"{proto['held_out_cutoffs'][-1]}) were run once. Cutoffs four weeks apart give overlapping {H}-week windows, so each week is scored up to "
          f"{H // 4} times. The point prediction is the simulation's central path (every shock at its median); ranges are the 5th-95th percentile of "
          f"{len(proto['seeds'])} runs per cutoff.", "", T["data"].format(**fmt), ""]
    L += ["Comparators, fixed before scoring, each applied to the organisation's own weekly series as known at the cutoff:", ""]
    L += [f"- {labels[c]}" for c in comps]
    L += ["", "Error measures: for weekly volume, the sum over organisation-weeks of absolute errors divided by the sum of actual "
          "volumes (WAPE), computed per cutoff and averaged over cutoffs; accuracy = 100 x (1 - WAPE). " +
          ("For the on-time share, the mean absolute error in percentage points over organisation-weeks; accuracy = 100 x (1 - error / mean actual share)."
           if "on_time" in metrics else "For time to close, the mean absolute percentage error of each agency's weekly median hours to close over agency-weeks; accuracy = 100 - that error."), ""]

    def table(block: dict, title: str) -> list[str]:
        out = [f"## {title}", "", "| Outcome | Simulation | " + " | ".join(labels[c] for c in comps) + " | Best classical | Error reduction | Accuracy (simulation) |",
               "|---|---:|" + "---:|" * len(comps) + "---|---:|---:|"]
        for key, s in block.items():
            base, grp = key.split(":")[0], (key.split(":")[1] if ":" in key else None)
            m = metrics[base]
            name = m["label"] + (f", {groups[grp]['label']}" if grp else "")
            out.append(f"| {name} | {err(key, m['measure'], s['errors']['simulation'])} | " + " | ".join(err(key, m["measure"], s["errors"][c]) for c in comps)
                       + f" | {labels[s['best_baseline']]} | {pct(s['error_reduction_pct'])} | {pct(s['accuracy_pct']['simulation'])} |")
        return out + [""]

    L += table(held, f"Held-out accuracy ({len(proto['held_out_cutoffs'])} cutoffs, {proto['held_out_cutoffs'][0]} to {proto['held_out_cutoffs'][-1]})")
    v = held["volume"]
    L += [f"Headline: the simulation's error in each {T['org']}'s weekly {T['unit']} was {pct(100 * v['errors']['simulation'])} against "
          f"{pct(100 * v['errors'][v['best_baseline']])} for the best classical forecast ({labels[v['best_baseline']]}), an error reduction of "
          f"{pct(v['error_reduction_pct'])}; accuracy {pct(v['accuracy_pct']['simulation'])} against {pct(v['accuracy_pct'][v['best_baseline']])}. "
          f"{v['n_predictions']:,} {T['org']}-week predictions over {v['n_windows']} cutoffs; the scored weeks run from {proto['held_out_cutoffs'][0]} to {span_end}. "
          "Negative error reduction means the simulation loses.", ""]
    L += table(allc, f"All cutoffs ({len(proto['cutoffs'])}, development and held out)")
    L += table(dev, f"Development cutoffs ({len(proto['dev_cutoffs'])}, used for design choices)")
    bh = ev["by_horizon"]["held_out"]
    L += ["## By weeks ahead (held out, weekly volume WAPE)", "", "| Weeks after the cutoff | Simulation | " + " | ".join(labels[c] for c in comps) + " |",
          "|---|---:|" + "---:|" * len(comps)]
    for hb, row in bh.items():
        L.append(f"| {hb} | {pct(100 * row['simulation'])} | " + " | ".join(pct(100 * row[c]) for c in comps) + " |")
    cov = ev["coverage90"]["held_out"]
    L += ["", f"The simulation's 90% range contained the actual weekly {T['unit']} of {pct(100 * cov)} of {T['org']}-weeks (held out).", ""]
    # where the simulation loses
    wins = [w for w in ev["windows"] if w["split"] == "held_out"]
    best = v["best_baseline"]
    lose = [w for w in wins if w["scores"]["volume"]["simulation"] > w["scores"]["volume"][best]]
    worst = sorted(wins, key=lambda w: w["scores"]["volume"]["simulation"] - w["scores"]["volume"][best], reverse=True)[:5]
    L += ["## Where the simulation loses", "",
          f"On weekly volume the simulation's error was larger than the best classical forecast's ({labels[best]}) at {len(lose)} of {len(wins)} held-out cutoffs. "
          "The five cutoffs where it lost most:", "", "| Cutoff | Simulation | " + labels[best] + " |", "|---|---:|---:|"]
    L += [f"| {w['cutoff']} | {pct(100 * w['scores']['volume']['simulation'])} | {pct(100 * w['scores']['volume'][best])} |" for w in worst]
    org_err: dict[str, list[float]] = {}
    for w in wins:
        for o in w["per_org"]:
            a = np.array([np.nan if x is None else x for x in o["volume_actual"]], dtype=float)
            s = np.array([np.nan if x is None else x for x in o["volume_simulation"]], dtype=float)
            b = np.array(o[f"volume_{best}"], dtype=float)
            org_err.setdefault(o["org"], []).append(float(np.nansum(np.abs(s - a)) - np.nansum(np.abs(b - a))))
    worst_org = sorted(org_err.items(), key=lambda kv: sum(kv[1]), reverse=True)[:5]
    L += ["", f"The {T['orgs']} whose summed absolute weekly error was most above the best classical forecast's, over the held-out cutoffs:", "",
          f"| {T['org'].capitalize()} | Cutoffs | Extra absolute error ({T['unit']}) |", "|---|---:|---:|"]
    L += [f"| {o} | {len(e)} | {sum(e):,.0f} |" for o, e in worst_org]
    for key in metrics:
        if key == "volume" or key not in held:
            continue
        s = held[key]
        if s["error_reduction_pct"] is not None and s["error_reduction_pct"] < 0:
            L += ["", f"On {metrics[key]['label'].lower()} the simulation loses to {labels[s['best_baseline']]} on the held-out cutoffs "
                  f"({err(key, metrics[key]['measure'], s['errors']['simulation'])} against {err(key, metrics[key]['measure'], s['errors'][s['best_baseline']])})."]
    L.append("")
    # staffing arithmetic inputs
    mu = v.get("mae_units") or {}
    bv = next(b for b in ev["business_validation"] if b["split"] == "held_out")
    L += ["## What the lower error means for staffing", "",
          f"Per {T['org']}-week the simulation missed by {num(mu.get('simulation'), 1)} {T['unit']} on average and the best classical forecast by "
          f"{num(mu.get(best), 1)}, against an average of {num(v['mean_actual'], 1)} {T['unit']} per {T['org']}-week. For the {proto['n_orgs']} {T['orgs']} together, "
          f"the average week held {num(bv['mean_actual'], 0)} {T['unit']}; the simulation's total missed by {num(bv['simulation_mae'], 0)} a week on average and the best "
          f"classical forecast's ({labels[bv['best_baseline']]}) by {num(bv['baseline_mae'][bv['best_baseline']], 0)}. Staff hours follow from these counts and a "
          f"handling time per {T['unit'][:-1]}, which the data do not record; `runs/{iid}/value_inputs.json` carries the counts with their paths in the evaluation.", ""]
    alt = ev.get("scenario_comparison") or []
    if alt:
        L += ["## Alternative", "", f"`{alt[0]['scenario']}` ran at the last {len(alt[0]['cutoffs'])} cutoffs with the same seeds ({alt[0]['runs']} runs); "
              "its predictions are simulated only and are shown in the Results tab.", ""]
    L += ["## Limitations", "",
          "This is a retrospective evaluation on public data. The design (agents, outcomes, grids) was chosen with the development cutoffs visible, "
          "and the general shape of the later series was public knowledge when the design was written; only the held-out scoring was run once "
          "after the freeze. Overlapping windows make neighbouring cutoffs' errors correlated.", "",
          "## Reproduction", "", "```bash", f"uv run python instances/{iid}/ingest/download.py", f"uv run orgsim ingest {iid}",
          f"uv run orgsim evaluate {iid}", f"uv run python instances/{iid}/reports/build_report.py", f"uv run python scripts/build_service_validation.py {iid}",
          f"uv run --extra dev pytest tests/test_service.py -q", "```", ""]
    (ROOT / "docs" / f"validation_{iid}.md").write_text("\n".join(L))

    # value inputs: every figure with its path inside evaluation.json
    def fig(name: str, path: str) -> dict:
        cur = ev
        for part in path.replace("]", "").replace("[", ".").split("."):
            cur = cur[int(part)] if isinstance(cur, list) else cur[part]
        return {"name": name, "value": cur, "path": path}
    bvi = next(i for i, b in enumerate(ev["business_validation"]) if b["split"] == "held_out")
    figs = [fig("headline_outcome_label", "protocol.metrics.volume.label"),
            fig("simulation_error_wape", "accuracy.held_out.volume.errors.simulation"),
            *[fig(f"comparator_error_wape_{c}", f"accuracy.held_out.volume.errors.{c}") for c in comps],
            fig("best_comparator", "accuracy.held_out.volume.best_baseline"),
            fig("error_reduction_pct", "accuracy.held_out.volume.error_reduction_pct"),
            fig("accuracy_pct_simulation", "accuracy.held_out.volume.accuracy_pct.simulation"),
            fig("mean_actual_per_org_week", "accuracy.held_out.volume.mean_actual"),
            fig("simulation_mae_per_org_week", "accuracy.held_out.volume.mae_units.simulation"),
            *[fig(f"comparator_mae_per_org_week_{c}", f"accuracy.held_out.volume.mae_units.{c}") for c in comps],
            fig("n_predictions_org_weeks", "accuracy.held_out.volume.n_predictions"),
            fig("n_cutoffs", "accuracy.held_out.volume.n_windows"),
            fig("held_out_cutoffs", "protocol.held_out_cutoffs"),
            fig("horizon_weeks", "protocol.horizon_weeks"),
            fig("n_orgs_per_cutoff", "protocol.n_orgs"),
            fig("total_weekly_volume_mean_actual", f"business_validation[{bvi}].mean_actual"),
            fig("total_weekly_volume_simulation_mae", f"business_validation[{bvi}].simulation_mae"),
            fig("total_weekly_volume_best_comparator", f"business_validation[{bvi}].best_baseline"),
            fig("coverage90_held_out", "coverage90.held_out")]
    for key in held:
        if key == "volume":
            continue
        figs += [fig(f"{key}_simulation_error", f"accuracy.held_out.{key}.errors.simulation"),
                 fig(f"{key}_best_comparator", f"accuracy.held_out.{key}.best_baseline"),
                 fig(f"{key}_mean_actual", f"accuracy.held_out.{key}.mean_actual"),
                 fig(f"{key}_error_reduction_pct", f"accuracy.held_out.{key}.error_reduction_pct")]
        best_k = held[key]["best_baseline"]
        figs.append(fig(f"{key}_best_comparator_error", f"accuracy.held_out.{key}.errors.{best_k}"))
    val = {"instance": iid, "evaluation": f"runs/{iid}/evaluation.json", "evaluation_sha256": hashlib.sha256(ev_path.read_bytes()).hexdigest(),
           "evaluation_generated": ev["generated"], "span": {"first_cutoff": proto["held_out_cutoffs"][0], "last_scored_day": str(span_end)},
           "accuracy_rule": "accuracy = 100 x (1 - error / mean actual); for WAPE and MAPE the error is already relative to the actual",
           "figures": figs}
    (ROOT / "runs" / iid / "value_inputs.json").write_text(json.dumps(val, indent=1))
    print(f"wrote docs/validation_{iid}.md and runs/{iid}/value_inputs.json")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("instance")
    build(ap.parse_args().instance)
