"""Write docs/validation_fedwork.md from runs/fedwork/evaluation.json and instances/fedwork/calibration/selection.json.
Every number is read from those files; nothing is typed in by hand.

    uv run python scripts/build_fedwork_validation.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TYPE_LABELS = {"quit": "Quits", "retire": "Retirements", "term": "Terminations (appointments ending, RIF)", "transfer": "Transfers to other agencies",
               "other": "Other", "drp": "Deferred resignations"}


def pct(v, d: int = 1) -> str:
    return "–" if v is None else f"{v:.{d}f}%"


def num(v) -> str:
    return "–" if v is None else f"{v:,.0f}"


def main() -> None:
    ev = json.loads((ROOT / "runs/fedwork/evaluation.json").read_text())
    sel = json.loads((ROOT / "instances/fedwork/calibration/selection.json").read_text())
    names = json.loads((ROOT / "instances/fedwork/data/normalized/agencies.json").read_text())["names"]
    labels = ev["comparator_labels"]; keys = list(labels)
    held = next(w for w in ev["windows"] if w["role"] == "held_out")
    acc = ev["accuracy"]
    L = ["# Validation: federal workforce separations after the 2025 changes (OPM)\n",
         "Numeric claims are generated by `scripts/build_fedwork_validation.py` from `runs/fedwork/evaluation.json` and `instances/fedwork/calibration/selection.json`.\n",
         "## Design\n",
         f"At each December cutoff every agency's employees become cohort twins (agency × age band × length of service × permanent appointment × full-time × supervisor; "
         f"{num(held['headcount_start'])} employees at the held-out cutoff). Each twin's monthly separation rate by type is fitted on records effective and published by the cutoff. "
         f"The world predicts each agency's separations in each month from {held['months'][0]} to {held['months'][1]} after the cutoff; the point prediction is the expected count averaged over "
         f"{ev['protocol']['seeds']} runs. Development cutoffs ({', '.join(w['cutoff'] for w in ev['windows'] if w['role'] == 'development')}) had no announced change and chose the specification; "
         f"the {held['cutoff']} cutoff is held out. For it, the return-to-office order and the deferred resignation offer enter on their announced dates with effects from earlier studies "
         "(`instances/fedwork/calibration/priors.yaml`). Agencies with fewer than 1,000 employees at the cutoff are scored as one group.\n",
         "## Development selection\n",
         f"Rule: {sel['rule']}. {len(sel['candidates'])} twin specifications were compared; the selected one ({sel['selected']['window_months']}-month rate window, shrinkage "
         f"{sel['selected']['shrink']}, {sel['selected']['season']} month pattern, {sel['selected_stock']} stock) had a mean development error of "
         f"{pct(min(r['mean_group_month_wape'] for r in sel['candidates']), 2)}. Exponential smoothing constants: " + ", ".join(f"{k} {v}" for k, v in sel['comparators']['ets'].items()) + ".\n",
         "## Error in each agency's monthly separations\n",
         "Sum of absolute errors over agency-months divided by actual separations (lower is better). Accuracy is 100 minus this error.\n",
         "| Cutoff | Role | Months | Actual separations | Simulation | " + " | ".join(labels[k] for k in keys) + " |",
         "|---|---|---|---:|---:|" + "---:|" * len(keys)]
    for w in ev["windows"]:
        s = w["scores"]
        L.append(f"| {w['cutoff']} | {w['role'].replace('_', '-')} | {w['months'][0]} to {w['months'][1]} | {num(s['simulation']['actual_total'])} | {pct(s['simulation']['group_month_wape'])} | "
                 + " | ".join(pct(s[k]["group_month_wape"]) for k in keys) + " |")
    L.append("")
    L.append("| Scope | Simulation | Best other | Error reduction | Simulation accuracy | Best other accuracy |\n|---|---:|---|---:|---:|---:|")
    for scope, lab in (("held_out", "Held out (2025)"), ("development", "Development (2022-2024)"), ("all", "All cutoffs")):
        g = acc[scope]["group_month_wape"]; b = g["best_comparator"]
        L.append(f"| {lab} | {pct(g['simulation'])} | {labels[b]} ({pct(g[b])}) | {pct(g['error_reduction_pct'])} | {pct(g['accuracy_pct']['simulation'])} | {pct(g['accuracy_pct'][b])} |")
    series = [k for k in keys if k != "programme"]
    gs = acc["held_out"]["group_month_wape"]; bs = min(series, key=lambda k: gs[k])
    L.append(f"\nAgainst the best series method alone ({labels[bs]}, {pct(gs[bs])}), the held-out simulation error of {pct(gs['simulation'])} is "
             f"{pct(100 * (1 - gs['simulation'] / gs[bs]))} lower. Negative error reduction means the simulation loses.\n")
    L.append("## Agency totals and the government-wide total\n")
    L.append("| Measure | Simulation | " + " | ".join(labels[k] for k in keys) + " |\n|---|---:|" + "---:|" * len(keys))
    for metric, lab in (("group_total_wape", "Error in each agency's total over the window, held out"), ("total_error_pct", "Government-wide total, held out (prediction minus actual, % of actual)")):
        L.append(f"| {lab} | {pct(held['scores']['simulation'][metric])} | " + " | ".join(pct(held["scores"][k][metric]) for k in keys) + " |")
    L.append(f"\nActual separations {held['months'][0]} to {held['months'][1]}: {num(held['scores']['simulation']['actual_total'])}; simulation {num(held['scores']['simulation']['predicted_total'])}.\n")
    L.append("| Month | Actual | Simulation (90% range) | " + " | ".join(labels[k] for k in keys) + " |\n|---|---:|---:|" + "---:|" * len(keys))
    m = held["monthly"]
    for i, mo in enumerate(m["months"]):
        L.append(f"| {mo} | {num(m['actual'][i])} | {num(m['simulation'][i])} ({num(m['simulation_band'][0][i])}-{num(m['simulation_band'][1][i])}) | " + " | ".join(num(m[k][i]) for k in keys) + " |")
    L.append("\n## Separations by type, held out\n")
    L.append("| Type | Actual | Simulation |\n|---|---:|---:|")
    for t, v in held["by_type"].items():
        L.append(f"| {TYPE_LABELS.get(t, t)} | {num(v['actual'])} | {num(v['simulation'])} |")
    L.append("\nDeferred resignations are the records OPM flags as such; their category in the data is a quit or a retirement.\n")
    L.append("## Where the simulation loses\n")
    dev = acc["development"]["group_month_wape"]
    L.append(f"- In the development years without a policy change the simulation's error ({pct(dev['simulation'])}) is higher than {labels[dev['best_comparator']]} ({pct(dev[dev['best_comparator']])}).")
    pg = acc["held_out"]["group_month_wape"]
    if "programme" in pg:
        L.append(f"- In 2025 the {labels['programme'].lower()}, which applies the same published effects to each agency as a whole, is closer ({pct(pg['programme'])} against {pct(pg['simulation'])}).")
    big = sorted(held["groups"].items(), key=lambda kv: -abs((kv[1]["simulation"] or 0) - (kv[1]["actual"] or 0)))[:8]
    L.append("- The largest agency misses over the held-out window:\n")
    L.append("| Agency | Actual | Simulation | " + " | ".join(labels[k] for k in keys) + " |\n|---|---:|---:|" + "---:|" * len(keys))
    for g, v in big:
        L.append(f"| {names.get(g, 'Other agencies') if g != 'OTHER' else 'Other agencies'} | {num(v['actual'])} | {num(v['simulation'])} | " + " | ".join(num(v[k]) for k in keys) + " |")
    alt = (ev.get("scenario_comparison") or [None])[0]
    if alt:
        t = alt["total"]
        L.append(f"\n## Alternative: no resignation offer\n\nWith the same {len(alt['seeds'])} seeds, separations from {held['months'][0]} to {held['months'][1]} are {num(t['alternative'])} without the "
                 f"offer against {num(t['baseline'])} with it ({num(t['difference'])}; 90% range {num(t['interval'][0])} to {num(t['interval'][1])}). This is a simulated alternative, not an observed estimate.\n")
    L.append("## Limitations\n")
    L.append("This is a retrospective evaluation: the design was chosen by people who knew the 2025 events in outline. The priors take published values as printed and the "
             "specification was chosen on development years only, but the policy channels themselves could not be tested before 2025. The simulation models only what was "
             "announced on 20-28 January 2025; reductions in force, later offers by individual agencies, the hiring freeze's effect on in-year hires and transfers, and probationary "
             "firings are not simulated (OPM withholds adverse-action codes, so most firings are also absent from the actual counts). OPM republishes files; this evaluation uses the "
             "pinned versions in `instances/fedwork/manifests/sources.json`, including revised versions of pre-2025 months. The frozen protocol is `docs/plans/fedwork_protocol.md`.\n")
    (ROOT / "docs/validation_fedwork.md").write_text("\n".join(L))
    print("wrote docs/validation_fedwork.md")


if __name__ == "__main__":
    main()
