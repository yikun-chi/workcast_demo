"""Write docs/validation_ctrip.md from runs/ctrip/evaluation.json and instances/ctrip/calibration/selection.json.
Every number is read from those files; nothing is typed in by hand.

    uv run python scripts/build_ctrip_validation.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def fmt(v, unit: str, signed: bool = False) -> str:
    if v is None:
        return "–"
    s = "+" if signed and v > 0 else ""
    if unit in ("%", "pp"):
        return f"{s}{v:.1f}{'%' if unit == '%' else ' pp'}"
    if unit == "SD":
        return f"{s}{v:.3f}"
    return f"{s}{v:,.1f}"


def main() -> None:
    ev = json.loads((ROOT / "runs/ctrip/evaluation.json").read_text())
    sel = json.loads((ROOT / "instances/ctrip/calibration/selection.json").read_text())
    fit = json.loads((ROOT / "instances/ctrip/calibration/fit.json").read_text())
    labels = ev["comparator_labels"]
    keys = list(labels)
    idx = ev["metric_index"]
    n = ev["population"]["n"]
    L: list[str] = []
    L.append("# Validation: work from home in a call centre (Ctrip, QJE 2015)\n")
    L.append("Numeric claims are generated by `scripts/build_ctrip_validation.py` from `runs/ctrip/evaluation.json` and `instances/ctrip/calibration/`.\n")
    L.append("## Design\n")
    L.append(f"Ctrip randomly assigned {n['1']} of {n['0'] + n['1']} volunteer call-centre employees to work from home four days a week from 6 December 2010; "
             f"the other {n['0']} stayed in the office. Each employee is a digital twin built from their pre-experiment characteristics and their own 2010 weekly record. "
             "Twins' weekly calls and performance scores move with home working by a published meta-analytic effect; their weekly quit risk combines the 2010 exit rate of "
             "call-centre staff with published tenure, age and turnover-intent effects. Every prior cites work published before the experiment's results appeared (February 2013). "
             f"The simulation runs {ev['protocol']['seeds']} times; point predictions are the mean and ranges cover 90% of runs. Scored weeks are 2010 week 50 to 2011 week 33; "
             "week 49, when the experiment began, is a transition week and is not scored.\n")
    L.append("## Development on 2010 data\n")
    L.append(f"The twin calibration was chosen before the experiment period was read, on two pseudo-changes inside 2010 (weeks {sel['pseudo_changes'][0]} and {sel['pseudo_changes'][1]}). "
             f"Rule: {sel['rule']}.\n")
    L.append("| Level estimator | Score (lower is better) |\n|---|---:|")
    for r in sel["candidates"]:
        c = r["candidate"]
        L.append(f"| {c['estimator']}{' ' + str(c['k']) + ' weeks' if 'k' in c else ''} | {r['score']:.3f} |")
    L.append("")
    L.append("| Exit-hazard spell threshold (weeks) | Mean absolute error in share leaving |\n|---:|---:|")
    for h in sel["hazard_candidates"]:
        L.append(f"| {h['min_spell']} | {h['mean_abs_error_pp']:.2f} pp |")
    s = sel["selected"]
    L.append(f"\nSelected: {s['estimator']} level, spell threshold {s['min_spell']} weeks. The fitted 2010 exit hazard is {100 * fit['exit_hazard']['weekly']:.3f}% a week "
             f"({fit['exit_hazard']['exits']} exits in {fit['exit_hazard']['person_weeks']:,} person-weeks of staff outside the experiment).\n")
    L.append("## Held-out result: the experiment period, scored once\n")
    L.append("| Measure | Actual (SE) | Simulation | " + " | ".join(labels[k] for k in keys) + " | Best other | Error reduction |")
    L.append("|---|---:|---:|" + "---:|" * len(keys) + "---|---:|")
    for m in ev["metrics"]:
        se = f" ({fmt(m['actual_se'], m['unit'])})" if m.get("actual_se") else ""
        signed = m["kind"] not in ("level", "attrition_level")
        L.append(f"| {m['label']} | {fmt(m['actual'], m['unit'], signed)}{se} | {fmt(m['simulated'], m['unit'], signed)} | "
                 + " | ".join(fmt(m["comparators"].get(k), m["unit"], signed) for k in keys)
                 + f" | {labels.get(m.get('best_comparator'), '–')} | {fmt(m.get('error_reduction_pct'), '%')} |")
    L.append("\nError reduction is 100 × (1 − simulation error / best other error); negative means the simulation loses. Standard errors of effects are from each person's change; "
             "standard errors of quit shares are binomial.\n")
    L.append("| Level | Simulation accuracy | " + " | ".join(labels[k] for k in keys) + " |\n|---|---:|" + "---:|" * len(keys))
    for m in ev["metrics"]:
        if "accuracy_pct" in m:
            L.append(f"| {m['label']} | {m['accuracy_pct']:.1f}% | " + " | ".join(fmt(m["comparator_accuracy_pct"].get(k), "%") for k in keys) + " |")
    L.append("\nAccuracy is 100 × (1 − |error| / actual).\n")
    wins = [m for m in ev["metrics"] if m.get("beats_best_comparator")]
    loses = [m for m in ev["metrics"] if m.get("beats_best_comparator") is False]
    L.append("## Where the simulation wins and loses\n")
    L.append("Closer than every other prediction: " + ("; ".join(m["label"] for m in wins) or "none") + ".\n")
    L.append("Further than the best other prediction: " + ("; ".join(f"{m['label']} (best: {labels[m['best_comparator']]})" for m in loses) or "none") + ".\n")
    for mid in ("calls_effect_pct", "attrition_effect_pp"):
        m = idx[mid]
        inside = "inside" if m.get("within_actual_ci95") else "outside"
        L.append(f"- {m['label']}: the simulation's {fmt(m['simulated'], m['unit'], True)} is {inside} the experiment's 95% interval "
                 f"({fmt(m['actual_ci95'][0], m['unit'], True)} to {fmt(m['actual_ci95'][1], m['unit'], True)}).")
    ao, ah = idx["attrition_office"], idx["attrition_home"]
    L.append(f"- Quits in the office group were {fmt(ao['actual'], '%')} against {fmt(ao['simulated'], '%')} predicted from the 2010 exit rate; in the home group "
             f"{fmt(ah['actual'], '%')} against {fmt(ah['simulated'], '%')}. The closest other prediction for the office group was {labels[ao['best_comparator']]} "
             f"at {fmt(ao['comparators'][ao['best_comparator']], '%')}.\n")
    alt = (ev.get("scenario_comparison") or [{}])[0]
    if alt.get("metrics"):
        c, a = alt["metrics"]["calls_effect_pct"], alt["metrics"]["attrition_effect_pp"]
        L.append("## Alternative: two home days a week\n")
        L.append(f"With the same {len(alt['seeds'])} seeds, the simulated effect on calls falls from {fmt(c['baseline'], '%', True)} to {fmt(c['alternative'], '%', True)} and the effect on quits "
                 f"from {fmt(a['baseline'], 'pp', True)} to {fmt(a['alternative'], 'pp', True)}. This is a simulated alternative, not an observed estimate; its size rests on the sourced "
                 "two-day share of the effect (`intensity_share_2d`).\n")
    L.append("## Limitations\n")
    L.append("This is a retrospective evaluation. The design was chosen by people who knew the published result in outline, although every prior takes the published "
             "meta-analytic value as printed and the specification was chosen on 2010 data only. The 2010 exit hazard comes from staff who disappear from the weekly "
             "panel, which is not the same record as the experiment's quits. The Dataverse deposit needs a guestbook form; the ingest uses the authors' public copy of "
             "the same files, pinned by SHA-256. The frozen protocol is `docs/plans/ctrip_protocol.md`.\n")
    (ROOT / "docs/validation_ctrip.md").write_text("\n".join(L))
    print("wrote docs/validation_ctrip.md")


if __name__ == "__main__":
    main()
