"""Render the client copy from copy_template.md, printing only figures from sealed/case_numbers.csv.

Fails if the template names an unknown figure, or if any digit is left in the rendered copy outside a sealed figure
(headings' list numbers and the product name "Microsoft 365" excepted). Also writes out/PROVENANCE.md: every figure
in the copy -> its formula -> the sealed inputs it reads -> their source file, SHA-256 and locator.

    python3 value_cases/05_render_copy.py
"""
from __future__ import annotations

import csv
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ALLOWED = [r"^### \d+\. ", r"Microsoft 365"]


def unbacked(marked: str) -> list[str]:
    """Snippets around any digit outside a sealed span (sealed spans are wrapped in \\x00 ... \\x01)."""
    bare = re.sub(r"\x00[^\x01]*\x01", "", marked)
    for pat in ALLOWED:
        bare = re.sub(pat, "", bare, flags=re.M)
    return re.findall(r".{0,30}\d.{0,30}", bare)


# the check must catch a typed-in figure and pass a sealed one
assert unbacked("saves about 20% in year one") and not unbacked("saves about \x0020%\x01 in year one")


def main() -> None:
    nums = {r["id"]: r for r in csv.DictReader((HERE / "sealed" / "case_numbers.csv").open())}
    inputs = {r["id"]: r for r in csv.DictReader((HERE / "sealed" / "inputs.csv").open())}
    tpl = (HERE / "copy_template.md").read_text()
    used: list[str] = []

    def sub(m: re.Match) -> str:
        k = m.group(1)
        if k not in nums:
            raise SystemExit(f"template names an unsealed figure: {k}")
        used.append(k)
        return "\x00" + nums[k]["display"] + "\x01"          # mark sealed spans for the check below
    marked = re.sub(r"\{\{(\w+)\}\}", sub, tpl)
    stray = unbacked(marked)
    if stray:
        raise SystemExit("unbacked numbers in copy:\n" + "\n".join(stray))
    copy = marked.replace("\x00", "").replace("\x01", "")
    (HERE / "out").mkdir(exist_ok=True)
    (HERE / "out" / "value_cases_client.md").write_text(copy)
    # ---- provenance
    lines = ["# Provenance: worked value case", "",
             "Generated by `05_render_copy.py`. Each figure printed in `out/value_cases_client.md`, the formula that produced it "
             "(`04_compute_cases.py`), and the sealed inputs it reads (`03_extract_inputs.py`) with their source file, SHA-256 and locator. "
             "Figures whose formula says `assumption` come from `assumptions.yaml` (illustrative client values).", "",
             "| Figure | Printed | Formula | Inputs (source, SHA-256 prefix, locator) |", "|---|---|---|---|"]
    for k in dict.fromkeys(used):
        r = nums[k]
        srcs = "; ".join(f"`{i}` = {inputs[i]['value']} ({inputs[i]['source']}, {inputs[i]['sha256'][:12]}, {inputs[i]['locator']})" for i in r["inputs"].split() if i in inputs)
        cell = srcs or ("assumptions.yaml" if r["formula"].startswith("assumption") else "derived from figures above")
        lines.append(f"| `{k}` | {r['display']} | {r['formula'].replace('|', chr(92) + '|')} | {cell.replace('|', chr(92) + '|')} |")
    (HERE / "out" / "PROVENANCE.md").write_text("\n".join(lines) + "\n")
    print(f"rendered out/value_cases_client.md with {len(used)} sealed figures ({len(set(used))} distinct); no unbacked numbers")


if __name__ == "__main__":
    main()
