"""Read every cited figure out of the hashed source snapshots into sealed/inputs.csv.

Each source file's SHA-256 is checked against its manifest before anything is read; a mismatch stops the run.
Every input row records where it came from (file, hash, and the table row, JSON path or text match used), so a
reader can reopen the snapshot and find the same value.

    python3 value_cases/03_extract_inputs.py
"""
from __future__ import annotations

import csv
import hashlib
import html
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
INTERNAL = HERE / "sources" / "internal"
EXTERNAL = sorted((HERE / "sources" / "external").iterdir())[-1]          # the latest dated snapshot


def verified(folder: Path) -> dict[str, str]:
    """file -> sha256, after checking every file in the folder against its manifest."""
    out = {}
    for m in json.loads((folder / "manifest.json").read_text()):
        h = hashlib.sha256((folder / m["file"]).read_bytes()).hexdigest()
        if h != m["sha256"]:
            raise SystemExit(f"hash mismatch: {folder / m['file']}")
        out[m["file"]] = h
    return out


rows: list[dict] = []


def add(id_: str, value: float, unit: str, folder: Path, file: str, locator: str, hashes: dict[str, str]) -> None:
    rows.append({"id": id_, "value": value, "unit": unit, "source": f"{folder.relative_to(HERE)}/{file}", "sha256": hashes[file], "locator": locator})
    print(f"{id_:34s} {value!r:>14} {unit:10s} {file} :: {locator}")


def table_row(md: str, label: str) -> list[str]:
    """Cells of the markdown table row whose first cell is `label`."""
    for line in md.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells and cells[0] == label:
            return cells
    raise SystemExit(f"row not found: {label}")


def text_of(path: Path) -> str:
    t = re.sub(r"<[^>]+>", " ", path.read_text(encoding="utf-8", errors="ignore"))
    return re.sub(r"\s+", " ", html.unescape(t))


def main() -> None:
    hi, he = verified(INTERNAL), verified(EXTERNAL)

    # ---- Trip.com hybrid-work trial (docs/validation.md, generated by the repository's build script)
    v = (INTERNAL / "validation_trip_bpi19.md").read_text()
    f = "validation_trip_bpi19.md"
    r = table_row(v, "Change in six-month attrition (hybrid minus office-only)")
    add("trip_attrition_effect_sim", float(r[1]), "pp", INTERNAL, f, "Trip.com table, row 'Change in six-month attrition', Simulation", hi)
    add("trip_attrition_effect_actual", float(r[2]), "pp", INTERNAL, f, "same row, Actual", hi)
    m = re.search(r"or (-?\d+\.\d+) percentage points of policy impact", v)
    add("trip_benchmark_effect", float(m.group(1)), "pp", INTERNAL, f, "text: 'or -2.45 percentage points of policy impact' (earlier-study scaling)", hi)
    r = table_row(v, "Change in work satisfaction (0–10 points)")
    add("trip_satisfaction_sim", float(r[1]), "points", INTERNAL, f, "row 'Change in work satisfaction (0–10 points)', Simulation", hi)
    add("trip_satisfaction_actual", float(r[2]), "points", INTERNAL, f, "same row, Actual", hi)
    add("trip_satisfaction_scale_max", 10.0, "points", INTERNAL, f, "row label '(0–10 points)'", hi)
    r = table_row(v, "Share of offered home days used")
    add("trip_takeup_sim", float(r[1]), "share", INTERNAL, f, "row 'Share of offered home days used', Simulation", hi)
    add("trip_takeup_actual", float(r[2]), "share", INTERNAL, f, "same row, Actual", hi)
    y = (INTERNAL / "trip_instance.yaml").read_text()
    m = re.search(r"let half of ([\d,]+) Airfare and IT employees in Shanghai work from home on Wednesdays and Fridays for (\w+) months", y)
    add("trip_employees", float(m.group(1).replace(",", "")), "people", INTERNAL, "trip_instance.yaml", "situation: 'let half of 1,612 Airfare and IT employees ...'", hi)
    add("trip_trial_months", {"six": 6.0}[m.group(2)], "months", INTERNAL, "trip_instance.yaml", "situation: '... for six months'", hi)

    # ---- purchase-to-pay (BPI Challenge 2019)
    r = table_row(v, "Cases completed within 14 days (pp)")
    add("bpi_completion_mae_sim", float(r[1]), "pp", INTERNAL, f, "row 'Cases completed within 14 days (pp)', Simulation MAE", hi)
    add("bpi_completion_mae_best", float(r[2].split()[0]), "pp", INTERNAL, f, "same row, best non-simulation MAE (training average)", hi)
    add("bpi_completion_error_reduction", float(r[3].rstrip("%")), "%", INTERNAL, f, "same row, Error reduction", hi)
    r = table_row(v, "Cases completed within 14 days (%)")
    add("bpi_completion_after_actual", float(r[2]), "%", INTERNAL, f, "row 'Cases completed within 14 days (%)', After, actual", hi)
    m = re.search(r"completion of (\d+\.\d+)% under observed staffing and (\d+\.\d+)% under the alternative", v)
    add("bpi_alt_completion_observed", float(m.group(1)), "%", INTERNAL, f, "text: 'completion of 11.79% under observed staffing'", hi)
    add("bpi_alt_completion_no_expansion", float(m.group(2)), "%", INTERNAL, f, "text: '11.78% under the alternative'", hi)
    m = re.search(r"multiplier: ([\d.]+)", (INTERNAL / "bpi19_no_expansion.yaml").read_text())
    add("bpi_no_expansion_multiplier", float(m.group(1)), "ratio", INTERNAL, "bpi19_no_expansion.yaml", "interventions: headcount_shift multiplier", hi)

    # ---- OpenRouter token demand (runs/openrouter/evaluation.json)
    ev = json.loads((INTERNAL / "openrouter_evaluation.json").read_text())
    f = "openrouter_evaluation.json"
    acc = ev["accuracy"]
    add("or_cutoffs", float(len(ev["windows"])), "count", INTERNAL, f, "len(windows)", hi)
    add("or_apps_per_cutoff", float(ev["protocol"]["n_apps"]), "count", INTERNAL, f, "protocol.n_apps", hi)
    add("or_company_predictions", float(sum(w["n_apps"] for w in ev["windows"])), "count", INTERNAL, f, "sum(windows[].n_apps)", hi)
    add("or_horizon_weeks", float(ev["protocol"]["horizon_weeks"]), "weeks", INTERNAL, f, "protocol.horizon_weeks", hi)
    add("or_1wk_error_sim", acc["by_horizon"]["1"]["simulation"], "%", INTERNAL, f, "accuracy.by_horizon['1'].simulation", hi)
    add("or_1wk_error_carry_forward", acc["by_horizon"]["1"]["carry_forward"], "%", INTERNAL, f, "accuracy.by_horizon['1'].carry_forward", hi)
    add("or_oneoff_error_sim", acc["by_class"]["burst"]["simulation"], "%", INTERNAL, f, "accuracy.by_class.burst.simulation", hi)
    add("or_oneoff_error_carry_forward", acc["by_class"]["burst"]["carry_forward"], "%", INTERNAL, f, "accuracy.by_class.burst.carry_forward", hi)
    ts = next(b for b in ev["business_validation"] if b["id"] == "top_spend")
    add("or_spend_mae_sim", ts["simulation_mae"], "$M", INTERNAL, f, "business_validation[top_spend].simulation_mae", hi)
    add("or_spend_mae_best", ts["baseline_mae"][ts["best_baseline"]], "$M", INTERNAL, f, f"business_validation[top_spend].baseline_mae.{ts['best_baseline']} (best)", hi)
    add("or_spend_actual_mean", sum(w["actual"] for w in ts["windows"]) / len(ts["windows"]), "$M", INTERNAL, f, "mean of business_validation[top_spend].windows[].actual", hi)
    add("or_first_cutoff_year", float(ev["windows"][0]["cutoff"][:4]), "year", INTERNAL, f, "windows[0].cutoff", hi)

    # ---- Ctrip work-from-home trial (Bloom et al. 2015), held-out evaluation
    f = "ctrip_evaluation.json"
    ct = json.loads((INTERNAL / f).read_text())["metric_index"]["perf_effect"]
    add("ctrip_perf_effect_sim", ct["simulated"], "SD", INTERNAL, f, "metric_index.perf_effect.simulated", hi)
    add("ctrip_perf_effect_actual", ct["actual"], "SD", INTERNAL, f, "metric_index.perf_effect.actual", hi)
    add("ctrip_perf_effect_literature", ct["comparators"]["literature"], "SD", INTERNAL, f, "metric_index.perf_effect.comparators.literature", hi)
    best = min(ct["comparator_errors"], key=ct["comparator_errors"].get)
    add("ctrip_perf_best_comparator_is_literature", float(best == "literature"), "flag", INTERNAL, f, "argmin of metric_index.perf_effect.comparator_errors", hi)

    # ---- BTOS AI use by sector and Stack Overflow questions after ChatGPT (adoption world), held-out cutoffs
    for inst, scale in (("btos_ai", 100.0), ("so_chatgpt", 1.0)):
        f = f"{inst}_evaluation.json"
        h = json.loads((INTERNAL / f).read_text())["accuracy"]["held_out"]["headline"]
        best = min((k for k in h["mae"] if k != "simulation"), key=h["mae"].get)
        add(f"{inst}_mae_sim", h["mae"]["simulation"] * scale, "level", INTERNAL, f, "accuracy.held_out.headline.mae.simulation", hi)
        add(f"{inst}_mae_best", h["mae"][best] * scale, "level", INTERNAL, f, f"accuracy.held_out.headline.mae.{best} (best of {len(h['mae']) - 1} comparators)", hi)
        add(f"{inst}_mean_actual", h["mean_actual"] * scale, "level", INTERNAL, f, "accuracy.held_out.headline.mean_actual", hi)
        add(f"{inst}_n_predictions", float(h["n_predictions"]), "count", INTERNAL, f, "accuracy.held_out.headline.n_predictions", hi)

    lab = json.loads((INTERNAL / "so_chatgpt_evaluation.json").read_text())["headline"]["mae"]["label"]
    m = re.search(r"per (\d+) weeks", lab)
    add("so_chatgpt_window_weeks", float(m.group(1)), "weeks", INTERNAL, "so_chatgpt_evaluation.json", f"headline.mae.label: '{lab}'", hi)

    # ---- external rates
    g = text_of(EXTERNAL / "gallup_replacement_cost.html")
    if "one-half to two times the employee's annual salary" not in g:
        raise SystemExit("Gallup sentence not found")
    add("gallup_replacement_low", 0.5, "x salary", EXTERNAL, "gallup_replacement_cost.html", "text: 'one-half to two times the employee's annual salary'", he)
    add("gallup_replacement_high", 2.0, "x salary", EXTERNAL, "gallup_replacement_cost.html", "same sentence, upper end", he)
    b = json.loads((EXTERNAL / "bls_oews_433031_median.json").read_text())
    d = b["Results"]["series"][0]["data"][0]
    add("bls_clerk_median_wage", float(d["value"]), "$/year", EXTERNAL, "bls_oews_433031_median.json", f"series OEUN000000000000043303113, {d['year']} annual", he)
    add("bls_clerk_wage_year", float(d["year"]), "year", EXTERNAL, "bls_oews_433031_median.json", "same row, year", he)
    t = text_of(EXTERNAL / "microsoft_copilot_pricing_announcement.html")
    m = re.search(r"Microsoft 365 Copilot will be priced at \$(\d+) per user per month", t)
    add("copilot_price_per_user_month", float(m.group(1)), "$/user/month", EXTERNAL, "microsoft_copilot_pricing_announcement.html", "text: 'Microsoft 365 Copilot will be priced at $30 per user per month'", he)
    t = text_of(EXTERNAL / "microsoft_learn_ptu_reservations.html")
    for phrase in ("excess reserved PTUs aren't used", "charged at the hourly, pay-as-you-go rate"):
        if phrase not in t:
            raise SystemExit(f"reservation mechanics phrase not found: {phrase}")
    add("reservation_unused_is_lost", 1.0, "flag", EXTERNAL, "microsoft_learn_ptu_reservations.html", "text: 'excess reserved PTUs aren't used' and 'charged at the hourly, pay-as-you-go rate'", he)

    with (HERE / "sealed" / "inputs.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["id", "value", "unit", "source", "sha256", "locator"])
        w.writeheader(); w.writerows(rows)
    print(f"wrote sealed/inputs.csv ({len(rows)} inputs)")


if __name__ == "__main__":
    main()
